/**
 * The site photos: turns each photo's source into
 * `public/img/<name>-{400,800,1200}.webp` and writes the manifest
 * (`scripts/photos/manifest.json`) that lib/image-loader.ts serves them from.
 *
 *   npx tsx scripts/image-variants.ts [--originals <dir>]
 *
 * `<dir>` holds the owner's originals, named `<name>.<jpg|jpeg|png|webp|heic>`,
 * and stays outside the repo: only the generated variants are committed. A
 * photo whose original has not arrived uses its stand-in, the copy the boards
 * draw (docs/boards/img), through the same pipeline; rerunning with the
 * original replaces it in place.
 */
import { existsSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { writeVariants, type Variant } from "./photos/core";

export const PUBLIC_IMG = "public/img";
export const IMG_URL = "/img";
export const MANIFEST = "scripts/photos/manifest.json";

export interface SitePhoto {
  name: string;
  /** The board's copy of the photo, used until the original arrives. */
  standIn: string;
}

/** The site's photos: the two portraits and the photo of the three of us. */
export const SITE_PHOTOS: readonly SitePhoto[] = [
  { name: "seth", standIn: "docs/boards/img/seth.jpg" },
  { name: "christine", standIn: "docs/boards/img/christine.jpg" },
  { name: "us-three", standIn: "docs/boards/img/us-three.jpg" },
];

export interface ManifestEntry {
  /** Where the variants came from: the owner's original or the stand-in. */
  source: "original" | "stand-in";
  /** Narrowest first. */
  variants: Variant[];
}

export interface Manifest {
  note: string;
  /** Keyed by the logical src a page passes to next/image, e.g. `/img/seth`. */
  images: Record<string, ManifestEntry>;
}

const EXTENSIONS = /\.(jpe?g|png|webp|heic)$/i;

function originalOf(dir: string | undefined, name: string): string | null {
  if (!dir || !existsSync(dir)) return null;
  const hit = readdirSync(dir).find(
    (f) => EXTENSIONS.test(f) && path.parse(f).name.toLowerCase() === name
  );
  return hit ? path.join(dir, hit) : null;
}

export async function buildVariants(
  root: string,
  originals?: string
): Promise<Manifest> {
  const images: Record<string, ManifestEntry> = {};
  for (const photo of SITE_PHOTOS) {
    const original = originalOf(originals, photo.name);
    const input = original ?? path.join(root, photo.standIn);
    const variants = await writeVariants(
      input,
      photo.name,
      path.join(root, PUBLIC_IMG),
      IMG_URL
    );
    images[`${IMG_URL}/${photo.name}`] = {
      source: original ? "original" : "stand-in",
      variants,
    };
  }
  const manifest: Manifest = {
    note: "Generated by scripts/image-variants.ts. Do not edit by hand.",
    images,
  };
  writeFileSync(
    path.join(root, MANIFEST),
    `${JSON.stringify(manifest, null, 2)}\n`
  );
  return manifest;
}

async function main() {
  const at = process.argv.indexOf("--originals");
  const originals = at >= 0 ? process.argv[at + 1] : undefined;
  if (at >= 0 && !originals) throw new Error("--originals needs a directory");
  const manifest = await buildVariants(process.cwd(), originals);
  for (const [src, entry] of Object.entries(manifest.images)) {
    const files = entry.variants.map((v) => path.basename(v.src)).join(", ");
    console.log(`${src} (${entry.source}): ${files}`);
  }
}

if (require.main === module) {
  main().catch((error: unknown) => {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  });
}
